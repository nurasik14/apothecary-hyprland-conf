#!/usr/bin/env bash
# apps/zen/build.sh — generate apps/zen/apothecary.css (+ apothecary-content.css) from the tokens:
#   light zen-vars.css at :root, dark zen-vars.css wrapped in @media (prefers-color-scheme: dark), then the
#   userChrome rules (apps/zen/userChrome-rules.css). One file serves both modes: Zen follows the desktop
#   colour scheme through the portal, so apply-mode.sh only has to set gsettings color-scheme.
# install.sh COPIES the result into the profile's chrome/ (the flatpak sandbox cannot follow symlinks into ~/.config/apothecary).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
tokens="$here/../../tokens/out"
strip() { grep -vE '^\s*/\*.*\*/\s*$' "$1"; }   # drop the generator comment lines

{
  echo "/* Apothecary Hyprland — Zen userChrome. GENERATED by apps/zen/build.sh from tokens/out/{light,dark}/zen-vars.css + apps/zen/userChrome-rules.css — edit those. */"
  echo "/* ---- light: Apothecary 薬屋 ---- */"
  strip "$tokens/light/zen-vars.css"
  echo "/* ---- dark: Inner Palace 后宫 ---- */"
  echo "@media (prefers-color-scheme: dark) {"
  strip "$tokens/dark/zen-vars.css" | sed 's/^/  /'
  echo "}"
  echo
  cat "$here/userChrome-rules.css"
} > "$here/apothecary.css"

{
  echo "/* Apothecary Hyprland — Zen userContent (about:blank / newtab / internal pages). GENERATED by apps/zen/build.sh. */"
  cat "$here/userContent-rules.css"
} > "$here/apothecary-content.css"
echo "built: $here/apothecary.css ($(wc -l < "$here/apothecary.css") lines), $here/apothecary-content.css"
