#!/usr/bin/env bash
# apps/install.sh — install the Apothecary application themes (LIGHT files linked, nothing applied).
#
# Safe by design: only adds theme files, `.pre-apothecary` backups, marker lines and the
# ~/.config/apothecary/<app>/current* symlinks. It does NOT change gsettings / the GTK theme —
# that is apps/apply-mode.sh <light|dark>. Reverse everything with apps/uninstall.sh.
# Idempotent: run it again after pulling the repo.
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

have jq || die "jq is required"
[[ -d "$TOKENS/light" && -d "$TOKENS/dark" ]] || die "tokens not built: run python3 tokens/build.py"

state_init
record_gsettings
[[ -e "$STATE_DIR/repo" ]] || ln -sfn "$REPO" "$STATE_DIR/repo"
mkdir -p "$STATE_DIR"/{kitty,fastfetch,rofi,gtk,qt6ct,superfile,cava,btop,starship,wlogout,swappy,zen,nvim}

MODE=light   # install links light; apply-mode flips

# ---------------------------------------------------------------- kitty
install_kitty() {
  local m
  for m in light dark; do link "$TOKENS/$m/kitty.conf" "$STATE_DIR/kitty/colors-$m.conf"; done
  link "$APPS/kitty/apothecary-$MODE.conf" "$STATE_DIR/kitty/current.conf"
  append_marker "$CFG/kitty/kitty.conf" "include ~/.config/apothecary/kitty/current.conf"   # the path is the marker (kitty forbids trailing comments on include)
}

# ---------------------------------------------------------------- fastfetch (+ Maomao logo)
install_fastfetch() {
  local art="$REPO/assets/art"
  link "$APPS/fastfetch/apothecary-$MODE.jsonc" "$STATE_DIR/fastfetch/current.jsonc"
  if [[ -f "$art/fastfetch-maomao.png" ]]; then
    link "$art/fastfetch-maomao.png" "$STATE_DIR/fastfetch/logo.png"
  else
    warn "assets/art/fastfetch-maomao.png missing (run assets/fetch-art.sh) — using ascii fallback"
    link "$APPS/fastfetch/apothecary-ascii.jsonc" "$STATE_DIR/fastfetch/current.jsonc"
  fi
  replace_with_symlink "$CFG/fastfetch/config.jsonc" "$STATE_DIR/fastfetch/current.jsonc"
}

# ---------------------------------------------------------------- rofi
install_rofi() {
  local conf="$CFG/rofi/config.rasi" orig
  # remember the theme the user had active (last @theme line wins in rofi)
  orig="$(grep -oP '^\s*@theme\s*"\K[^"]+' "$conf" 2>/dev/null | tail -n1 || true)"
  state_set_once '.keys["rofi.original_theme"]' "${orig:-__absent__}"
  link "$TOKENS/$MODE/rofi-colors.rasi" "$STATE_DIR/rofi/colors.rasi"
  link "$APPS/rofi/apothecary.rasi" "$STATE_DIR/rofi/current.rasi"
  append_marker "$conf" "@theme \"~/.config/apothecary/rofi/current.rasi\" /* $MARK */"
}

# ---------------------------------------------------------------- GTK 3/4 + xsettingsd
build_gtk_css() {   # concatenate tokens + our tweaks into real files (GTK @import paths are brittle through symlinks)
  local m
  for m in light dark; do
    { echo "/* apothecary gtk3 — $m (generated by apps/install.sh: tokens gtk-colors.css + apps/gtk/gtk3-tweaks.css) */"
      cat "$TOKENS/$m/gtk-colors.css" "$APPS/gtk/gtk3-tweaks.css"; } > "$STATE_DIR/gtk/gtk3-$m.css"
    { echo "/* apothecary gtk4 — $m (generated: gtk-colors.css + gtk4-vars.css + apps/gtk/gtk4-tweaks.css) */"
      cat "$TOKENS/$m/gtk-colors.css" "$TOKENS/$m/gtk4-vars.css" "$APPS/gtk/gtk4-tweaks.css"; } > "$STATE_DIR/gtk/gtk4-$m.css"
  done
}
install_gtk() {
  build_gtk_css
  link "$STATE_DIR/gtk/gtk3-$MODE.css" "$STATE_DIR/gtk/current-gtk3.css"
  link "$STATE_DIR/gtk/gtk4-$MODE.css" "$STATE_DIR/gtk/current-gtk4.css"
  link "$APPS/gtk/xsettingsd-$MODE.conf" "$STATE_DIR/gtk/current-xsettingsd.conf"
  replace_with_symlink "$CFG/gtk-3.0/gtk.css" "$STATE_DIR/gtk/current-gtk3.css"
  replace_with_symlink "$CFG/gtk-4.0/gtk.css" "$STATE_DIR/gtk/current-gtk4.css"
  replace_with_symlink "$CFG/xsettingsd/xsettingsd.conf" "$STATE_DIR/gtk/current-xsettingsd.conf"
  # cursor for dark mode (optional download, no sudo, non-fatal)
  if [[ ! -d "$HOME/.icons/Bibata-Modern-Classic" ]] && have curl; then
    local tmp; tmp="$(mktemp -d)"
    if curl -fsSL --max-time 60 -o "$tmp/b.tar.xz" \
         "https://github.com/ful1e5/Bibata_Cursor/releases/latest/download/Bibata-Modern-Classic.tar.xz" \
       && tar -xJf "$tmp/b.tar.xz" -C "$tmp" 2>/dev/null && [[ -d "$tmp/Bibata-Modern-Classic" ]]; then
      mkdir -p "$HOME/.icons" && mv "$tmp/Bibata-Modern-Classic" "$HOME/.icons/" && state_add created "$HOME/.icons/Bibata-Modern-Classic"
      log "cursor: installed Bibata-Modern-Classic to ~/.icons"
    else
      warn "cursor: could not download Bibata-Modern-Classic (dark mode keeps Bibata-Modern-Ice)"
    fi
    rm -rf "$tmp"
  fi
}

# ---------------------------------------------------------------- Qt: qt6ct + Kvantum
install_qt() {
  local m
  mkdir -p "$CFG/qt6ct/colors" "$CFG/Kvantum"
  for m in light dark; do
    link "$TOKENS/$m/qt6ct-colors.conf" "$CFG/qt6ct/colors/apothecary-$m.conf"; state_add files "$CFG/qt6ct/colors/apothecary-$m.conf"
  done
  link "$CFG/qt6ct/colors/apothecary-$MODE.conf" "$STATE_DIR/qt6ct/current.conf"
  [[ -d "$APPS/kvantum/ApothecaryLight" ]] || bash "$APPS/kvantum/build.sh"
  link "$APPS/kvantum/ApothecaryLight" "$CFG/Kvantum/ApothecaryLight"; state_add files "$CFG/Kvantum/ApothecaryLight"
  link "$APPS/kvantum/ApothecaryDark"  "$CFG/Kvantum/ApothecaryDark";  state_add files "$CFG/Kvantum/ApothecaryDark"
  # record originals now (apply-mode edits them); nothing applied yet
  [[ -f "$CFG/qt6ct/qt6ct.conf" ]] || { mkdir -p "$CFG/qt6ct"; printf '[Appearance]\n' > "$CFG/qt6ct/qt6ct.conf"; state_add created "$CFG/qt6ct/qt6ct.conf"; }
  [[ -f "$CFG/Kvantum/kvantum.kvconfig" ]] || { printf '[General]\n' > "$CFG/Kvantum/kvantum.kvconfig"; state_add created "$CFG/Kvantum/kvantum.kvconfig"; }
  backup_file "$CFG/qt6ct/qt6ct.conf"; backup_file "$CFG/Kvantum/kvantum.kvconfig"
}

# ---------------------------------------------------------------- superfile
install_superfile() {
  local m
  mkdir -p "$CFG/superfile/theme"
  for m in light dark; do
    link "$APPS/superfile/apothecary-$m.toml" "$CFG/superfile/theme/apothecary-$m.toml"; state_add files "$CFG/superfile/theme/apothecary-$m.toml"
  done
  local conf="$CFG/superfile/config.toml"
  [[ -f "$conf" ]] || { warn "superfile config.toml missing — run spf once"; return 0; }
  backup_file "$conf"
  set_kv "$conf" theme "apothecary-$MODE" toml
  set_kv "$conf" transparent_background true toml-raw
  set_kv "$conf" default_open_file_preview true toml-raw
  set_kv "$conf" nerdfont true toml-raw
  # editor: only fill it when the user left it empty
  if grep -qE '^editor\s*=\s*""' "$conf"; then set_kv "$conf" editor nvim toml; fi
  have zoxide && set_kv "$conf" zoxide_support true toml-raw || true
}

# ---------------------------------------------------------------- cava
install_cava() {
  link "$APPS/cava/config-$MODE" "$STATE_DIR/cava/current"
  replace_with_symlink "$CFG/cava/config" "$STATE_DIR/cava/current"
}

# ---------------------------------------------------------------- btop
install_btop() {
  local m
  mkdir -p "$CFG/btop/themes"
  for m in light dark; do
    link "$TOKENS/$m/btop.theme" "$CFG/btop/themes/apothecary-$m.theme"; state_add files "$CFG/btop/themes/apothecary-$m.theme"
  done
  [[ -f "$CFG/btop/btop.conf" ]] || { mkdir -p "$CFG/btop"; : > "$CFG/btop/btop.conf"; state_add created "$CFG/btop/btop.conf"; }
  set_kv "$CFG/btop/btop.conf" color_theme "apothecary-$MODE" toml
  set_kv "$CFG/btop/btop.conf" theme_background False toml-raw
}

# ---------------------------------------------------------------- starship
build_starship() {   # preset + both palettes → one real file whose `palette =` line apply-mode flips
  { cat "$APPS/starship/apothecary.toml"; echo; cat "$TOKENS/light/starship-palette.toml"; echo; cat "$TOKENS/dark/starship-palette.toml"; } \
    > "$STATE_DIR/starship/apothecary.toml"
  sed -i -E "s|^palette = .*|palette = \"apothecary_$MODE\"|" "$STATE_DIR/starship/apothecary.toml"
}
install_starship() {
  build_starship
  mkdir -p "$CFG/starship"
  link "$STATE_DIR/starship/apothecary.toml" "$CFG/starship/apothecary.toml"; state_add files "$CFG/starship/apothecary.toml"
  # select it the way JaKooLit's ChangeStarshipPrompt.sh does: ~/.config/starship.toml is a symlink to the preset
  replace_with_symlink "$CFG/starship.toml" "$CFG/starship/apothecary.toml"
}

# ---------------------------------------------------------------- spicetify
install_spicetify() {
  mkdir -p "$CFG/spicetify/Themes"
  link "$APPS/spicetify/Apothecary" "$CFG/spicetify/Themes/Apothecary"; state_add files "$CFG/spicetify/Themes/Apothecary"
  if have spicetify; then
    local ini="$CFG/spicetify/config-xpui.ini"
    state_set_once '.keys["spicetify.current_theme"]' "$(spicetify config current_theme 2>/dev/null || true)"
    state_set_once '.keys["spicetify.color_scheme"]'  "$(spicetify config color_scheme 2>/dev/null || true)"
    [[ -f "$ini" ]] && backup_file "$ini"
    spicetify config current_theme Apothecary color_scheme "$MODE" >/dev/null && spicetify apply >/dev/null 2>&1 \
      || warn "spicetify apply failed (is Spotify installed/backed up?)"
  else
    warn "spicetify CLI not installed — theme files placed in ~/.config/spicetify/Themes/Apothecary only"
  fi
}

# ---------------------------------------------------------------- Zen browser (flatpak sandbox: real files, not symlinks)
install_zen() {
  local prof chrome
  prof="$(find "$CFG/zen" -maxdepth 1 -type d -name '*.Default (release)' 2>/dev/null | head -1)"
  [[ -n "$prof" ]] || prof="$(find "$CFG/zen" -maxdepth 1 -type d -name '*.Default*' 2>/dev/null | head -1)"
  [[ -n "$prof" ]] || { warn "zen profile not found under ~/.config/zen"; return 0; }
  chrome="$prof/chrome"; mkdir -p "$chrome"
  [[ -f "$APPS/zen/apothecary.css" ]] || bash "$APPS/zen/build.sh"
  cp -f "$APPS/zen/apothecary.css" "$chrome/apothecary.css"; state_add files "$chrome/apothecary.css"
  cp -f "$APPS/zen/apothecary-content.css" "$chrome/apothecary-content.css"; state_add files "$chrome/apothecary-content.css"
  append_marker "$chrome/userChrome.css"  "@import url(\"apothecary.css\"); /* $MARK */"
  append_marker "$chrome/userContent.css" "@import url(\"apothecary-content.css\"); /* $MARK */"
  append_marker "$prof/user.js" "user_pref(\"toolkit.legacyUserProfileCustomizations.stylesheets\", true); // $MARK"
  state_set_once '.keys["zen.profile"]' "$prof"
}

# ---------------------------------------------------------------- nvim (never touches ~/.config/nvim)
install_nvim() {
  local site="$HOME/.local/share/nvim/site" m
  mkdir -p "$site/colors" "$site/lua/apothecary"
  for m in light dark; do
    link "$APPS/nvim/colors/apothecary-$m.lua" "$site/colors/apothecary-$m.lua";        state_add files "$site/colors/apothecary-$m.lua"
    link "$TOKENS/$m/nvim-palette.lua"         "$site/lua/apothecary/palette_$m.lua";    state_add files "$site/lua/apothecary/palette_$m.lua"
  done
  link "$APPS/nvim/lua/apothecary/theme.lua" "$site/lua/apothecary/theme.lua"; state_add files "$site/lua/apothecary/theme.lua"
  link "$APPS/nvim/lua/apothecary/init.lua"  "$site/lua/apothecary/init.lua";  state_add files "$site/lua/apothecary/init.lua"
}

# ---------------------------------------------------------------- wlogout
build_wlogout() {
  local m
  rm -rf "$STATE_DIR/wlogout/icons"; cp -r "$APPS/wlogout/icons" "$STATE_DIR/wlogout/icons"
  for m in light dark; do
    { echo "/* apothecary wlogout — $m (generated: tokens wlogout-vars.css + apps/wlogout/style.css) */"
      cat "$TOKENS/$m/wlogout-vars.css"
      sed -e "s|@ICONS@|$STATE_DIR/wlogout/icons|g" -e "s|@MODE@|$m|g" "$APPS/wlogout/style.css"; } > "$STATE_DIR/wlogout/style-$m.css"
  done
}
install_wlogout() {
  build_wlogout
  link "$STATE_DIR/wlogout/style-$MODE.css" "$STATE_DIR/wlogout/current.css"
  link "$APPS/wlogout/layout" "$STATE_DIR/wlogout/current-layout"
  replace_with_symlink "$CFG/wlogout/style.css" "$STATE_DIR/wlogout/current.css"
  replace_with_symlink "$CFG/wlogout/layout"    "$STATE_DIR/wlogout/current-layout"
}

# ---------------------------------------------------------------- swappy
install_swappy() {
  link "$APPS/swappy/config-$MODE" "$STATE_DIR/swappy/current"
  replace_with_symlink "$CFG/swappy/config" "$STATE_DIR/swappy/current"
}

# ---------------------------------------------------------------- run
for app in kitty fastfetch rofi gtk qt superfile cava btop starship spicetify zen nvim wlogout swappy; do
  log "── $app"; "install_$app"
done
echo light > "$STATE_DIR/apps-mode.installed"
log "done. Files linked for LIGHT; nothing applied. Run: apps/apply-mode.sh light|dark|off"
