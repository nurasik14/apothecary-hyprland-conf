def wlogout(m, name):
    L = ["/* " + HEADER + " */", f"/* wlogout (GTK3 CSS) — Apothecary {name}: @import url(\"wlogout-vars.css\"); */"]
    for k, v in m.items():
        if isinstance(v, str) and v.startswith("#"):
            L.append(f"@define-color apo_{k} {v if alpha_of(v)==1 else css_rgba(v)};")
    return "\n".join(L)

def palette_json(m, name):
    flat = {"mode": name, "name": m["name"], "is_dark": m["is_dark"]}
    for k, v in m.items():
        if isinstance(v, str) and v.startswith("#"): flat[k] = v
    for i, c in enumerate(m["ansi"]):  flat[f"ansi{i}"] = c
    for i, c in enumerate(m["ink"]):   flat[f"ink{i}"] = c
    for i, c in enumerate(m["paper"]): flat[f"paper{i}"] = c
    return json.dumps(flat, indent=2, ensure_ascii=False)

