# ---------------------------------------------------------------- helpers
def hex6(c):           return c.lstrip("#")[:6].lower()
def hex8(c):           # ensure rrggbbaa
    h = c.lstrip("#").lower()
    return h if len(h) == 8 else h + "ff"
def alpha_of(c):
    h = c.lstrip("#")
    return int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
def rgb_tuple(c):
    h = hex6(c); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def hypr(c):           # Hyprland colour literal
    h = c.lstrip("#").lower()
    return f"rgba({h})" if len(h) == 8 else f"rgb({h})"
def hypr_rgba(c, a):   return f"rgba({hex6(c)}{int(round(a*255)):02x})"
def argb(c):           # qt6ct: #AARRGGBB
    h = c.lstrip("#").lower()
    return f"#{h[6:8] if len(h)==8 else 'ff'}{h[:6]}"
def css_rgba(c, a=None):
    r, g, b = rgb_tuple(c); a = alpha_of(c) if a is None else a
    return f"rgba({r}, {g}, {b}, {a:.2f})"
def sgr(c):
    r, g, b = rgb_tuple(c); return f"38;2;{r};{g};{b}"
def lum(c):
    r, g, b = [v / 255 for v in rgb_tuple(c)]
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def contrast(a, b):
    la, lb = lum(a), lum(b)
    if la < lb: la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)
def blend(fg, bg, a):  # composite fg over bg with alpha a -> #rrggbb
    f, b = rgb_tuple(fg), rgb_tuple(bg)
    return "#" + "".join(f"{int(round(f[i]*a + b[i]*(1-a))):02x}" for i in range(3))
def mix(a, b, t):      return blend(b, a, t)
def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not text.endswith("\n"): text += "\n"
    path.write_text(text, encoding="utf-8")

