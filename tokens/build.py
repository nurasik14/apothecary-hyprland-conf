def qt6ct(m, name):
    # QPalette order used by qt5ct/qt6ct (21 roles):
    # WindowText, Button, Light, Midlight, Dark, Mid, Text, BrightText, ButtonText, Base, Window, Shadow,
    # Highlight, HighlightedText, Link, LinkVisited, AlternateBase, ToolTipBase, ToolTipText, PlaceholderText, Accent
    isd = m["is_dark"]
    light_ = mix(m["bg2"], "#ffffff", 0.35) if not isd else m["surfaceAlt"]
    midlight = m["bg2"] if not isd else mix(m["surfaceAlt"], m["text"], 0.08)
    dark_ = m["ink"][3] if not isd else m["ink"][0]
    mid = m["hairline"]
    active = [m["text"], m["bg1"], light_, midlight, dark_, mid, m["text"], m["seal"], m["text"], m["surface"], m["bg1"], m["ink"][0] if not isd else "#000000",
              m["accent"], m["textOnAccent"], m["link"], m["plum"], m["surfaceAlt"], m["bg2"], m["text"], m["textMuted"], m["accent"]]
    inactive = list(active); inactive[12] = m["accentSoft"]; inactive[13] = m["textOnAccent"]
    dis = list(active); dis[0] = m["textMuted"]; dis[6] = m["textMuted"]; dis[8] = m["textMuted"]; dis[9] = m["bg1"]; dis[12] = m["hairline"]; dis[13] = m["textMuted"]
    row = lambda arr: ", ".join(argb(c) for c in arr)
    return "\n".join([f"; {HEADER}", f"; qt6ct / qt5ct colour scheme — Apothecary {name}", "[ColorScheme]",
                      f"active_colors={row(active)}", f"disabled_colors={row(dis)}", f"inactive_colors={row(inactive)}"])

