# ---------------------------------------------------------------- validation
def validate(outdir):
    errs = []
    for f in outdir.glob("*.toml"):
        try: tomllib.loads(f.read_text())
        except Exception as e: errs.append(f"{f.name}: {e}")
    for f in list(outdir.glob("*.json")):
        try: json.loads(f.read_text())
        except Exception as e: errs.append(f"{f.name}: {e}")
    for f in outdir.glob("*.jsonc"):
        txt = re.sub(r"^\s*//.*$", "", f.read_text(), flags=re.M)
        try: json.loads(txt)
        except Exception as e: errs.append(f"{f.name}: {e}")
    rasi = (outdir / "rofi-colors.rasi").read_text()
    body = re.sub(r"/\*.*?\*/", "", rasi, flags=re.S)
    if not re.fullmatch(r"\s*\*\s*\{(\s*[a-zA-Z0-9_-]+\s*:\s*[^;{}]+;)+\s*\}\s*", body):
        errs.append("rofi-colors.rasi: does not match `* { name: value; ... }`")
    for line in (outdir / "hyprland-colors.conf").read_text().splitlines():
        if line.startswith("$") and not re.fullmatch(r"\$[A-Za-z0-9_]+ = rgba?\([0-9a-f]{6,8}\)", line): errs.append("hyprland: " + line)
    qt = (outdir / "qt6ct-colors.conf").read_text()
    for row in re.findall(r"=(.*)", qt):
        n = len(row.split(","))
        if n != 21: errs.append(f"qt6ct: row has {n} colours, expected 21")
    k = (outdir / "kitty.conf").read_text()
    for i in range(16):
        if not re.search(rf"^color{i}\s+#[0-9a-f]{{6}}", k, re.M): errs.append(f"kitty: color{i} missing")
    sp = (outdir / "superfile-theme.toml").read_text()
    want = {"code_syntax_highlight","full_screen_fg","full_screen_bg","gradient_color","file_panel_fg","file_panel_bg","file_panel_border","file_panel_border_active",
            "file_panel_top_directory_icon","file_panel_top_path","file_panel_item_selected_fg","file_panel_item_selected_bg","footer_fg","footer_bg","footer_border",
            "footer_border_active","sidebar_fg","sidebar_bg","sidebar_title","sidebar_border","sidebar_border_active","sidebar_item_selected_fg","sidebar_item_selected_bg",
            "sidebar_divider","modal_fg","modal_bg","modal_border_active","modal_cancel_fg","modal_cancel_bg","modal_confirm_fg","modal_confirm_bg","help_menu_hotkey",
            "help_menu_title","cursor","correct","error","hint","cancel"}
    have = set(re.findall(r"^([a-z_]+)\s*=", sp, re.M))
    if want - have: errs.append(f"superfile: missing keys {sorted(want-have)}")
    return errs

# ---------------------------------------------------------------- contrast audit
def audit(m, name):
    grounds = ["bg0", "bg1", "bg2", "surface", "surfaceAlt"]
    rows, worst = [], (99, "", "")
    for role in m["text_safe"]:
        for g in grounds:
            v = contrast(m[role], m[g]); rows.append((role, g, v, v >= 4.5))
            if v < worst[0]: worst = (v, role, g)
    for role in m["ui_safe"]:
        for g in grounds:
            v = contrast(m[role], m[g]); rows.append((role + " (ui)", g, v, v >= 3.0))
    extra = [("titlebarText", "titlebar"), ("textOnAccent", "accent"), ("textOnSeal", "seal"), ("textOnAccent", "success"), ("selectionText", blend(m["accent"], m["surface"], alpha_of(m["selection"])))]
    for a, b in extra:
        v = contrast(m[a], m[b] if b in m else b); rows.append((a, b if b in m else "selection∘surface", v, v >= 4.5))
    for i, c in enumerate(m["ansi"]):
        if i in (0, 7, 15): continue
        v = contrast(c, m["surface"]); rows.append((f"ansi{i}", "surface", v, v >= (3.0 if i == 8 else 4.5)))
    return rows, worst

def contrast_markdown():
    out = ["| mode | foreground | ground | ratio | ok |", "|---|---|---|---|---|"]
    summary = {}
    for name, m in TOK["modes"].items():
        rows, worst = audit(m, name)
        summary[name] = worst
        for r in rows:
            out.append(f"| {name} | {r[0]} | {r[1]} | {r[2]:.2f} | {'✓' if r[3] else '✗'} |")
    return "\n".join(out), summary

# ---------------------------------------------------------------- main
def build():
    writers = {
        "hyprland-colors.conf": hyprland_colors, "kitty.conf": kitty, "rofi-colors.rasi": rofi, "gtk-colors.css": gtk_css,
        "gtk4-vars.css": lambda m, n: css_vars(m, n), "qt6ct-colors.conf": qt6ct, "superfile-theme.toml": superfile, "cava.conf": cava,
        "btop.theme": btop, "starship-palette.toml": starship, "spicetify-color.ini": spicetify, "zen-vars.css": zen,
        "nvim-palette.lua": nvim, "fastfetch-colors.jsonc": fastfetch, "hyprlock-vars.conf": hyprlock, "wlogout-vars.css": wlogout,
        "palette.json": palette_json,
    }
    all_errs = []
    for name, m in TOK["modes"].items():
        d = OUT / name
        for fname, fn in writers.items():
            write(d / fname, fn(m, name))
        errs = validate(d)
        all_errs += [f"[{name}] {e}" for e in errs]
        print(f"built tokens/out/{name}/ ({len(writers)} files){' — ERRORS: ' + '; '.join(errs) if errs else ' ✓'}")
    md, summary = contrast_markdown()
    write(OUT / "contrast.md", "# Contrast audit (generated)\n\n" + md)
    write(OUT / "shared.json", json.dumps(S, indent=2, ensure_ascii=False))
    for name, w in summary.items():
        print(f"worst text pair {name}: {w[1]} on {w[2]} = {w[0]:.2f}:1")
    if "--check" in sys.argv:
        for name, m in TOK["modes"].items():
            rows, _ = audit(m, name)
            fails = [r for r in rows if not r[3]]
            print(f"[{name}] {len(rows)} pairs, {len(fails)} failing")
            for r in fails: print(f"   FAIL {r[0]} on {r[1]} = {r[2]:.2f}")
    if all_errs:
        print("\n".join(all_errs)); sys.exit(1)

if __name__ == "__main__":
    build()
